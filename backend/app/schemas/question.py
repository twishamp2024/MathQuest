"""Pydantic schemas for questions and question generation."""

from datetime import datetime
from typing import Optional, List, Any
from pydantic import BaseModel, Field, ConfigDict


class QuestionConstraint(BaseModel):
    """Input constraints passed from the adaptive engine to the generator."""
    topic_id: str
    concept_id: str
    learning_objective: str
    difficulty: int = Field(ge=1, le=5)
    question_format: str = Field(pattern="^(multiple_choice|numeric|comparison|fraction_text)$")
    expected_answer_type: str = Field(pattern="^(integer|float|fraction|choice|text)$")
    min_numeric_value: float = -1000.0
    max_numeric_value: float = 10000.0
    age_group: str = "8-14"
    remedial_target: Optional[str] = None
    target_misconception: Optional[str] = None
    questions_to_avoid: List[str] = []


class GeneratedQuestionPayload(BaseModel):
    """Structured question definition generated by either AI or offline bank."""
    question_text: str = Field(min_length=3, max_length=500)
    topic_id: str
    concept_id: str
    difficulty: int = Field(ge=1, le=5)
    question_format: str = Field(pattern="^(multiple_choice|numeric|comparison|fraction_text)$")
    options: Optional[List[str]] = None
    correct_answer: str = Field(min_length=1, max_length=128)
    expected_answer_type: str = "integer"
    explanation_steps: List[str] = Field(default_factory=list)
    common_misconceptions: dict[str, str] = Field(default_factory=dict)
    hint_small: Optional[str] = None
    hint_detailed: Optional[str] = None


class QuestionResponse(BaseModel):
    """Child-facing question payload sent over the API (omitting correct_answer!)."""
    model_config = ConfigDict(from_attributes=True)

    question_id: str
    session_id: Optional[str] = None
    topic_id: str
    topic_title: str
    concept_id: str
    concept_title: str
    difficulty: int
    question_text: str
    question_format: str
    options: Optional[List[str]] = None
    has_small_hint: bool = True
    has_detailed_hint: bool = True
    recommendation_reason: Optional[str] = None
    created_at: datetime
